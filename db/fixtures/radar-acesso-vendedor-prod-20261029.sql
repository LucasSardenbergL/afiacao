CREATE OR REPLACE FUNCTION public.radar_irmaos_por_raiz(p_cnpjs text[])
 RETURNS TABLE(cnpj text, irmaos_na_fila integer, irmaos_clientes integer, cliente_nome text)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
BEGIN
  IF NOT COALESCE(private.cap_carteira_ler(auth.uid()), false) THEN
    RAISE EXCEPTION 'forbidden: carteira' USING ERRCODE = '42501';
  END IF;
  IF COALESCE(cardinality(p_cnpjs), 0) > 200 THEN
    RAISE EXCEPTION 'radar_irmaos_por_raiz: no máximo 200 CNPJs por chamada (veio %)', cardinality(p_cnpjs)
      USING ERRCODE = '22023';
  END IF;

  RETURN QUERY
  WITH pedidos AS (
    SELECT DISTINCT x AS cnpj, left(x, 8) AS raiz
      FROM unnest(p_cnpjs) AS u(x)
     WHERE x ~ '^[0-9A-Z]{12}[0-9]{2}$'
  ),
  clientes AS (
    SELECT d.doc, d.nome FROM public.radar_docs_clientes() d
     WHERE left(d.doc, 8) IN (SELECT raiz FROM pedidos)
    UNION
    SELECT r.cnpj, r.razao_social FROM public.radar_empresas r
     WHERE r.ja_cliente AND left(r.cnpj, 8) IN (SELECT raiz FROM pedidos)
  )
  SELECT
    p.cnpj,
    (SELECT count(*)::integer FROM public.radar_empresas r
      WHERE left(r.cnpj, 8) = p.raiz AND r.cnpj <> p.cnpj
        AND NOT r.ja_cliente AND r.prospeccao_status <> 'descartado'),
    (SELECT count(DISTINCT c.doc)::integer FROM clientes c
      WHERE left(c.doc, 8) = p.raiz AND c.doc <> p.cnpj),
    (SELECT c.nome FROM clientes c
      WHERE left(c.doc, 8) = p.raiz AND c.doc <> p.cnpj AND c.nome IS NOT NULL
      ORDER BY c.doc LIMIT 1)
  FROM pedidos p
  ORDER BY p.cnpj;
END;
$function$
;
CREATE OR REPLACE FUNCTION public.radar_kpis()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_uid uuid := auth.uid();
  v_lote text;
  v_novos integer;
  v_a_contatar integer;
  v_em_conversa integer;
  v_virou_mes integer;
BEGIN
  IF NOT COALESCE(public.pode_ver_carteira_completa(v_uid), false) THEN
    RAISE EXCEPTION 'forbidden: gestor/master only';
  END IF;

  SELECT mes_referencia, COALESCE(novos, 0) INTO v_lote, v_novos
    FROM public.radar_ingest_state
   WHERE status = 'complete'
   ORDER BY mes_referencia DESC LIMIT 1;

  SELECT count(*) INTO v_a_contatar FROM public.radar_empresas
   WHERE prospeccao_status = 'a_contatar' AND ja_cliente = false
     AND (v_lote IS NULL OR ultimo_lote = v_lote);
  SELECT count(*) INTO v_em_conversa FROM public.radar_empresas
   WHERE prospeccao_status = 'em_conversa';
  SELECT count(*) INTO v_virou_mes FROM public.radar_empresas
   WHERE prospeccao_status = 'virou_cliente'
     AND prospeccao_atualizado_em >= date_trunc('month', now(), 'America/Sao_Paulo');

  RETURN jsonb_build_object(
    'lote', v_lote, 'novos', COALESCE(v_novos, 0),
    'a_contatar', v_a_contatar, 'em_conversa', v_em_conversa,
    'virou_cliente_mes', v_virou_mes);
END $function$
;
CREATE OR REPLACE FUNCTION public.radar_prospects_para_rota(p_municipio_codigo text, p_limit integer DEFAULT 30)
 RETURNS TABLE(cnpj text, razao_social text, nome_fantasia text, logradouro text, numero text, complemento text, bairro text, municipio_nome text, uf text, cep text, telefone1 text, telefone2 text, prospeccao_status text, lat double precision, lng double precision, geocode_status text, "precision" text)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN
  IF NOT COALESCE(public.pode_ver_carteira_completa((SELECT auth.uid())), false) THEN
    RAISE EXCEPTION 'forbidden: gestor/master only';
  END IF;
  IF p_municipio_codigo IS NULL OR btrim(p_municipio_codigo) = '' THEN
