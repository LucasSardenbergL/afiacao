CREATE OR REPLACE FUNCTION public.radar_resolver_conflito_cadastro(p_id bigint, p_versao_vista integer, p_nota text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_uid uuid := (SELECT auth.uid());
  v_nota text := left(NULLIF(btrim(p_nota), ''), 500);
  v_cnpj text;
  v_versao integer;
BEGIN
  IF NOT COALESCE(public.pode_ver_carteira_completa(v_uid), false) THEN
    RAISE EXCEPTION 'forbidden: gestor/master only';
  END IF;
  IF v_nota IS NULL THEN RAISE EXCEPTION 'nota obrigatória: diga o que foi conferido no Omie'; END IF;
  SELECT c.cnpj INTO v_cnpj FROM public.radar_cadastro_conflitos c WHERE c.id = p_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'conflito não encontrado: %', p_id; END IF;
  -- Mesma ordem de trava das gravações (empresa → conflito): registrar × resolver se enfileiram, sem deadlock.
  PERFORM 1 FROM public.radar_empresas WHERE cnpj = v_cnpj FOR UPDATE;

  -- Concorrência otimista NO PRÓPRIO UPDATE: ocorrência registrada depois da leitura da tela (versao mudou) ou
  -- resolução de outra aba → 0 linhas → RD004; nada que ninguém viu é encerrado.
  UPDATE public.radar_cadastro_conflitos
     SET resolvido_em = now(), resolvido_por = v_uid, nota_resolucao = v_nota, versao = versao + 1
   WHERE id = p_id AND versao = p_versao_vista AND resolvido_em IS NULL
  RETURNING versao INTO v_versao;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'RADAR_CONFLITO_MUDOU: o conflito % mudou ou já foi resolvido desde a leitura (versão vista %) — releia', p_id,
      COALESCE(p_versao_vista::text, '∅') USING ERRCODE = 'RD004';
  END IF;
  RETURN jsonb_build_object('ok', true, 'versao', v_versao);
END $function$
;
CREATE OR REPLACE FUNCTION public.radar_salvar_geocode(p_cnpj text, p_lat double precision DEFAULT NULL::double precision, p_lng double precision DEFAULT NULL::double precision, p_status text DEFAULT 'ok'::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_uid uuid := (SELECT auth.uid());
BEGIN
  IF NOT COALESCE(public.pode_ver_carteira_completa(v_uid), false) THEN
    RAISE EXCEPTION 'forbidden: gestor/master only';
  END IF;
  IF p_cnpj IS NULL OR p_cnpj !~ '^[0-9]{14}$' THEN RAISE EXCEPTION 'cnpj inválido'; END IF;
  IF p_status IS NULL OR p_status NOT IN ('ok','falhou') THEN RAISE EXCEPTION 'status inválido'; END IF;
  IF p_status = 'ok' THEN
    IF p_lat IS NULL OR p_lng IS NULL
       OR p_lat < -90 OR p_lat > 90 OR p_lng < -180 OR p_lng > 180 THEN
      RAISE EXCEPTION 'lat/lng inválidos para status ok';
    END IF;
  END IF;
  UPDATE public.radar_empresas SET
    lat            = CASE WHEN p_status = 'ok' THEN p_lat ELSE NULL END,
    lng            = CASE WHEN p_status = 'ok' THEN p_lng ELSE NULL END,
    geocoded_em    = now(),
    geocode_status = p_status,
    updated_at     = now()
  WHERE cnpj = p_cnpj;
  IF NOT FOUND THEN RAISE EXCEPTION 'empresa não encontrada: %', p_cnpj; END IF;
  RETURN jsonb_build_object('ok', true, 'status', p_status);
END $function$
;
CREATE OR REPLACE FUNCTION public.registrar_contato_radar(p_cnpj text, p_acao text, p_nota text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_uid uuid := auth.uid();
  v_status_atual text;
  v_existing uuid;
  v_id uuid;
BEGIN
  IF NOT COALESCE(public.pode_ver_carteira_completa(v_uid), false) THEN
    RAISE EXCEPTION 'forbidden: gestor/master only';
  END IF;
  IF p_cnpj IS NULL OR p_cnpj !~ '^[0-9A-Z]{12}[0-9]{2}$' THEN
    RAISE EXCEPTION 'cnpj inválido';
  END IF;
  IF p_acao NOT IN ('a_contatar','contatado_sem_resposta','em_conversa','descartado','virou_cliente') THEN
    RAISE EXCEPTION 'ação inválida: %', p_acao;
  END IF;

  SELECT prospeccao_status INTO v_status_atual
    FROM public.radar_empresas WHERE cnpj = p_cnpj FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'empresa não encontrada: %', p_cnpj; END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended(v_uid::text||':'||p_cnpj||':'||p_acao||':radar', 0));
  SELECT id INTO v_existing FROM public.radar_contatos
   WHERE criado_por = v_uid AND cnpj = p_cnpj AND acao = p_acao
     AND created_at > now() - interval '2 minutes'
   ORDER BY created_at DESC LIMIT 1;
  IF v_existing IS NOT NULL THEN
    RETURN jsonb_build_object('id', v_existing, 'deduped', true);
  END IF;

  INSERT INTO public.radar_contatos (cnpj, acao, nota, criado_por, status_anterior)
  VALUES (p_cnpj, p_acao, p_nota, v_uid, v_status_atual)
  RETURNING id INTO v_id;

  UPDATE public.radar_empresas SET
    prospeccao_status = p_acao,
    prospeccao_atualizado_em = now(),
    descarte_motivo = CASE WHEN p_acao = 'descartado' THEN p_nota ELSE NULL END,
    updated_at = now()
  WHERE cnpj = p_cnpj;

  RETURN jsonb_build_object('id', v_id, 'deduped', false);
END $function$
;
CREATE OR REPLACE FUNCTION public._radar_cadastro_conflito_gravar(p_cnpj text, p_motivo text, p_codigo_recebido text, p_detalhe text, p_uid uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
DECLARE
  v_codigo text := NULLIF(btrim(p_codigo_recebido), '');
  v_detalhe text := left(NULLIF(btrim(p_detalhe), ''), 1000);
  v_vinculo text;
  v_outro text;
  v_linha public.radar_cadastro_conflitos;
BEGIN
  IF p_uid IS NULL THEN RAISE EXCEPTION 'autor obrigatório'; END IF;
  IF p_motivo IS NULL OR p_motivo NOT IN ('vinculo_divergente', 'codigo_de_outro_cnpj', 'lookup_divergente', 'lookup_ambiguo') THEN
    RAISE EXCEPTION 'motivo inválido: %', p_motivo;
  END IF;
  IF v_codigo IS NOT NULL AND v_codigo !~ '^[1-9][0-9]{0,18}$' THEN RAISE EXCEPTION 'código Omie inválido: %', v_codigo; END IF;
  IF v_detalhe IS NULL THEN RAISE EXCEPTION 'detalhe obrigatório'; END IF;

  SELECT NULLIF(btrim(e.omie_codigo_cliente), '') INTO v_vinculo FROM public.radar_empresas e WHERE e.cnpj = p_cnpj;
  IF NOT FOUND THEN RAISE EXCEPTION 'empresa não encontrada: %', p_cnpj; END IF;
  IF v_codigo IS NOT NULL THEN
    SELECT e.cnpj INTO v_outro FROM public.radar_empresas e WHERE e.omie_codigo_cliente = v_codigo AND e.cnpj <> p_cnpj;
  END IF;

  -- O servidor re-confere o que sabe; a alegação que ele DESMENTE não vira aviso (RD003). Não exige o ledger: o caso
  -- "Omie devolveu K, a confirmação não gravou, a retomada achou V≠K" é justamente evidência a guardar (Codex, c).
  IF p_motivo = 'vinculo_divergente' AND (v_codigo IS NULL OR v_vinculo IS NULL OR v_vinculo = v_codigo) THEN
    RAISE EXCEPTION 'RADAR_CONFLITO_NAO_CONFIRMADO: CNPJ % tem vínculo %, recebido % — não há divergência', p_cnpj,
      COALESCE(v_vinculo, '∅'), COALESCE(v_codigo, '∅') USING ERRCODE = 'RD003';
  END IF;
  IF p_motivo = 'codigo_de_outro_cnpj' AND v_outro IS NULL THEN
    RAISE EXCEPTION 'RADAR_CONFLITO_NAO_CONFIRMADO: cliente Omie % não está vinculado a outro CNPJ', COALESCE(v_codigo, '∅')
      USING ERRCODE = 'RD003';
  END IF;
  -- lookup_divergente / lookup_ambiguo (Omie com 2+ códigos para o documento — edge omie-vendas-sync v1.27, #3362): só a
  -- edge viu o Omie — relato do gestor, não verificável pelo banco (a tela diz isso).

  INSERT INTO public.radar_cadastro_conflitos AS t
    (cnpj, motivo, codigo_recebido, codigo_vinculado, cnpj_do_codigo, detalhe, criado_por, ultimo_por)
  VALUES (p_cnpj, p_motivo, v_codigo, v_vinculo, v_outro, v_detalhe, p_uid, p_uid)
  ON CONFLICT (cnpj, motivo, (COALESCE(codigo_recebido, ''))) WHERE resolvido_em IS NULL
  DO UPDATE SET ocorrencias = t.ocorrencias + 1, versao = t.versao + 1, ultima_em = now(), ultimo_por = EXCLUDED.ultimo_por,
                codigo_vinculado = EXCLUDED.codigo_vinculado, cnpj_do_codigo = EXCLUDED.cnpj_do_codigo, detalhe = EXCLUDED.detalhe
  RETURNING t.* INTO v_linha;
  RETURN to_jsonb(v_linha);
END $function$
;
CREATE OR REPLACE FUNCTION public.radar_atribuir_tarefa(p_cnpj text, p_dias_retomada integer DEFAULT 7)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_uid uuid := (SELECT auth.uid());
  v_razao text; v_fantasia text; v_municipio text; v_uf text; v_tel text;
  v_existing uuid; v_id uuid; v_desc text;
  v_dias integer := GREATEST(1, LEAST(COALESCE(p_dias_retomada, 7), 90));
BEGIN
  IF NOT COALESCE(public.pode_ver_carteira_completa(v_uid), false) THEN
    RAISE EXCEPTION 'forbidden: gestor/master only';
  END IF;
  IF p_cnpj IS NULL OR p_cnpj !~ '^[0-9A-Z]{12}[0-9]{2}$' THEN RAISE EXCEPTION 'cnpj inválido'; END IF;

  SELECT razao_social, nome_fantasia, municipio_nome, uf, telefone1
    INTO v_razao, v_fantasia, v_municipio, v_uf, v_tel
    FROM public.radar_empresas WHERE cnpj = p_cnpj;
  IF NOT FOUND THEN RAISE EXCEPTION 'empresa não encontrada: %', p_cnpj; END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended(v_uid::text||':'||p_cnpj||':tarefa:radar', 0));
  SELECT id INTO v_existing FROM public.tarefas
   WHERE created_by = v_uid AND empresa = 'oben' AND customer_user_id IS NULL
     AND status = 'aberta' AND descricao LIKE '%CNPJ '||p_cnpj||'%'
     AND created_at > now() - interval '2 minutes'
   ORDER BY created_at DESC LIMIT 1;
  IF v_existing IS NOT NULL THEN
    RETURN jsonb_build_object('id', v_existing, 'deduped', true);
  END IF;

  v_desc := 'Prospecção: ' || COALESCE(NULLIF(v_fantasia,''), NULLIF(v_razao,''), p_cnpj)
            || ' · ' || COALESCE(v_municipio,'?') || '/' || COALESCE(v_uf,'?')
            || COALESCE(' · tel ' || NULLIF(v_tel,''), '')
            || ' · CNPJ ' || p_cnpj;

  INSERT INTO public.tarefas (
    descricao, categoria, customer_user_id, assigned_to, created_by, empresa,
    modo, due_date, interacao_tipo, auto_satisfy_mode, status
  ) VALUES (
    v_desc, 'ligar', NULL, v_uid, v_uid, 'oben',
    'data', ((now() AT TIME ZONE 'America/Sao_Paulo')::date + v_dias), NULL, 'off', 'aberta'
  ) RETURNING id INTO v_id;

  RETURN jsonb_build_object('id', v_id, 'deduped', false);
END $function$
;
