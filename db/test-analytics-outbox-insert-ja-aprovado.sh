#!/usr/bin/env bash
# ╔══════════════════════════════════════════════════════════════════════════════════╗
# ║  PROVA PG17 — db/aplicar-analytics-outbox-insert-ja-aprovado.sql                  ║
# ║      bash db/test-analytics-outbox-insert-ja-aprovado.sh > /tmp/t.log 2>&1; echo "exit=$?"
# ║  (NÃO pipe pra tail — engole o exit≠0.)                                           ║
# ║                                                                                  ║
# ║  O que esta prova existe para pegar:                                             ║
# ║   1. O BUG (B): pedido INSERIDO já aprovado — o que a RPC sayerlack_importar_     ║
# ║      pedido_portal faz — emitia só 'criada' no corpo de PROD (2026-10-16: 3 de 3). ║
# ║      O corpo de prod entra pela migration de 2026-10-11 e o md5 é CONFERIDO: se o ║
# ║      fixture não for a prod, a prova não prova nada.                              ║
# ║   2. O ramo novo (C): INSERT já aprovado = 2 linhas (criada E aprovada); os       ║
# ║      ramos velhos (UPDATE aprova/expira/cancela) seguem iguais; fail-open vivo.    ║
# ║   3. O BACKFILL (M): só pedidos importados do portal, ocorrido_em = aprovado_em,  ║
# ║      idempotente; órfã de OUTRA origem NÃO entra (precisão > recall).             ║
# ║   4. FALSIFICAÇÃO: sabotar o ramo e o predicado do backfill tem de dar VERMELHO   ║
# ║      — na PÓS do arquivo e na asserção desta prova.                               ║
# ╚══════════════════════════════════════════════════════════════════════════════════╝
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export PGVER=17
PORT="${PGPORT_TEST:-5488}"
SLUG="analytics-outbox-insert-ja-aprovado"
DATA="$(mktemp -d "/tmp/pgtest-${SLUG}.XXXXXX")/data"
RODADA="$(dirname "$DATA")"
export LC_ALL=C LANG=C

# shellcheck disable=SC1091  # helper versionado ao lado, em db/lib/
. "$REPO_ROOT/db/lib/pg-harness.sh"

MAE="$REPO_ROOT/supabase/migrations/20260825214545_analytics_outbox.sql"
PRED="$REPO_ROOT/supabase/migrations/20261011150000_reposicao_recusa_definitiva_portal_servidor.sql"
ARQ="$REPO_ROOT/db/aplicar-analytics-outbox-insert-ja-aprovado.sql"
for f in "$MAE" "$PRED" "$ARQ"; do [ -f "$f" ] || { echo "arquivo ausente: $f"; exit 1; }; done
PRED_MD5='049e1b52b0c41950456268409ecb927f'   # md5(prosrc) de PROD, psql-ro 2026-10-18

cleanup() { "$PGBIN/pg_ctl" -D "$DATA" stop -m immediate >/dev/null 2>&1 || true; rm -rf "$RODADA"; }
trap cleanup EXIT

"$PGBIN/initdb" -D "$DATA" -U postgres -E UTF8 --locale=C >/dev/null
"$PGBIN/pg_ctl" -D "$DATA" -o "-p $PORT -k /tmp" -l "$RODADA/pg.log" -w start >/dev/null
"$PGBIN/createdb" -p "$PORT" -h /tmp -U postgres prove
P()  { "$PGBIN/psql" -X -p "$PORT" -h /tmp -U postgres -d prove -v ON_ERROR_STOP=1 "$@"; }
Pq() { P -tA "$@"; }

PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); echo "  ✅ $1"; }
bad() { FAIL=$((FAIL+1)); echo "  ❌ $1"; }
eq()  { if [ "$2" = "$3" ]; then ok "$1 (=$2)"; else bad "$1 — esperado [$3], veio [$2]"; fi; }

# ── ZONA 1: stubs + a tabela-fonte (só as colunas que trigger, view e backfill leem) ──────
P -q -f "$REPO_ROOT/db/stubs-supabase.sql"
P -q <<'SQL'
CREATE OR REPLACE FUNCTION auth.uid()  RETURNS uuid LANGUAGE sql STABLE AS $f$ SELECT nullif(current_setting('test.uid',  true), '')::uuid $f$;
CREATE OR REPLACE FUNCTION auth.role() RETURNS text LANGUAGE sql STABLE AS $f$ SELECT nullif(current_setting('test.role', true), '') $f$;
ALTER ROLE service_role BYPASSRLS;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'app_role') THEN
    CREATE TYPE public.app_role AS ENUM ('master','employee','customer');
  END IF;
END $$;
CREATE TABLE IF NOT EXISTS public.user_roles (user_id uuid NOT NULL, role public.app_role NOT NULL);
CREATE OR REPLACE FUNCTION cron.schedule(p_name text, p_sched text, p_cmd text) RETURNS bigint LANGUAGE sql AS $f$
  INSERT INTO cron.job(jobid, jobname, schedule, command, active)
  VALUES ((SELECT coalesce(max(jobid), 0) + 1 FROM cron.job), p_name, p_sched, p_cmd, true) RETURNING jobid;
$f$;
CREATE OR REPLACE FUNCTION cron.unschedule(p_name text) RETURNS boolean LANGUAGE sql AS $f$ DELETE FROM cron.job WHERE jobname = p_name RETURNING true; $f$;
CREATE TABLE public.pedido_compra_sugerido (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status text NOT NULL DEFAULT 'pendente_aprovacao',
  aprovado_por text, aprovado_em timestamptz, cancelado_em timestamptz,
  condicao_origem text, origem_evento_tipo text,
  criado_em timestamptz NOT NULL DEFAULT now(), atualizado_em timestamptz NOT NULL DEFAULT now()
);
SQL

# ── ZONA 2: migration-mãe (outbox + trigger v1) + corpo de PROD (2026-10-11) ────────────
P -q -f "$MAE" >/dev/null
awk '/^CREATE OR REPLACE FUNCTION public\.analytics_outbox_pedido_compra\(\)/{f=1} f{print} f && /^\$function\$;/{exit}' "$PRED" > "$RODADA/pred.sql"
P -q -f "$RODADA/pred.sql" >/dev/null
md5vivo() { Pq -c "SELECT md5(prosrc) FROM pg_proc WHERE oid = 'public.analytics_outbox_pedido_compra'::regproc;"; }
linhas() { Pq -c "SELECT count(*) FROM public.analytics_outbox WHERE chave_dedup LIKE 'pcs:$1:%';"; }
evento() { Pq -c "SELECT count(*) FROM public.analytics_outbox WHERE chave_dedup = 'pcs:$1:reposicao.$2';"; }
echo "=== setup pronto (PG17 :$PORT) ==="
eq "Z1 fixture = PROD: md5(prosrc) do corpo predecessor" "$(md5vivo)" "$PRED_MD5"

# ── ZONA 3 (B): o bug, no corpo de PROD ─────────────────────────────────────────────────
echo "-- grupo B: baseline (corpo de prod) --"
P -q <<'SQL'
-- as 3 órfãs reais (2026-10-16): importadas do portal, nascem aprovadas e disparadas
INSERT INTO public.pedido_compra_sugerido (id, status, aprovado_por, aprovado_em, condicao_origem, criado_em)
VALUES (3644, 'disparado', '414a9727', '2026-10-16 01:45:15.585889+00', 'importado_portal', '2026-10-16 01:45:15.585889+00'),
       (3669, 'disparado', '414a9727', '2026-10-16 22:03:50.904670+00', 'importado_portal', '2026-10-16 22:03:50.904670+00'),
       (3670, 'disparado', '414a9727', '2026-10-16 22:12:04.529065+00', 'importado_portal', '2026-10-16 22:12:04.529065+00');
-- controles do backfill: importado ANTES da RPC existir (impossível em prod; é o controle negativo do piso)
-- e órfã de OUTRA origem (inserida aprovada por outro caminho) — nenhum dos dois pode ser preenchido
INSERT INTO public.pedido_compra_sugerido (id, status, aprovado_por, aprovado_em, condicao_origem, criado_em)
VALUES (9001, 'disparado', 'x', '2026-10-01 10:00:00+00', 'importado_portal', '2026-10-01 10:00:00+00'),
       (9002, 'disparado', 'x', '2026-10-16 12:00:00+00', 'default_a_vista', '2026-10-16 12:00:00+00');
SQL
eq "B1 corpo de PROD: INSERT ja aprovado emite SO criada (1 linha)" "$(linhas 3669)" "1"
eq "B2 corpo de PROD: nenhuma 'aprovada' para as 3 importadas" \
   "$(Pq -c "SELECT count(*) FROM public.analytics_outbox WHERE evento='reposicao.sugestao_aprovada';")" "0"

# ── ZONA 4 (M): aplicar o arquivo real ──────────────────────────────────────────────────
echo "-- grupo M: o arquivo (TRAVA → PRE → CREATE → backfill → POS) --"
P -q -f "$ARQ" > "$RODADA/apply1.log" 2>&1 || { bad "M1 arquivo nao aplicou: $(tail -c 400 "$RODADA/apply1.log")"; exit 1; }
ok "M1 aplicou com ON_ERROR_STOP (PRE aceitou o predecessor; POS passou)"
ESTE="$(grep -E -- '-- este arquivo \(medido em PG17\)' "$ARQ" | grep -oE "[0-9a-f]{32}|MD5_DESTE_ARQUIVO" | head -1)"
eq "M2 md5 vivo apos aplicar = o que o arquivo declara como 'este' (PRE idempotente de verdade)" "$(md5vivo)" "$ESTE"
P -q -f "$ARQ" > "$RODADA/apply2.log" 2>&1 || { bad "M3 re-aplicar falhou: $(tail -c 400 "$RODADA/apply2.log")"; exit 1; }
ok "M3 re-aplicar e idempotente (PRE aceita 'este'; backfill ON CONFLICT)"
eq "M4 backfill: as 3 importadas ganharam 'aprovada'" \
   "$(Pq -c "SELECT count(*) FROM public.analytics_outbox WHERE evento='reposicao.sugestao_aprovada' AND props->>'backfill' = 'insert_ja_aprovado_2026-10-18';")" "3"
eq "M5 backfill: ocorrido_em = aprovado_em do pedido" \
   "$(Pq -c "SELECT count(*) FROM public.analytics_outbox o JOIN public.pedido_compra_sugerido p ON o.chave_dedup='pcs:'||p.id||':reposicao.sugestao_aprovada' WHERE p.id IN (3644,3669,3670) AND o.ocorrido_em = p.aprovado_em;")" "3"
eq "M6 backfill: 1 linha por pedido mesmo apos 2 applies (dedup)" "$(evento 3669 sugestao_aprovada)" "1"
eq "M7 backfill NAO toca importado anterior ao piso (9001)" "$(evento 9001 sugestao_aprovada)" "0"
eq "M8 backfill NAO toca orfa de outra origem (9002) — precisao > recall" "$(evento 9002 sugestao_aprovada)" "0"
eq "M9 backfill: props no formato do trigger (sugestao_id, aprovacao_humana=true)" \
   "$(Pq -c "SELECT props->>'sugestao_id' || '|' || (props->>'aprovacao_humana') FROM public.analytics_outbox WHERE chave_dedup='pcs:3670:reposicao.sugestao_aprovada';")" "3670|true"

# ── ZONA 5 (C): o corpo novo, transição a transição ─────────────────────────────────────
echo "-- grupo C: comportamento do corpo novo --"
P -q -c "INSERT INTO public.pedido_compra_sugerido (id) VALUES (101);" >/dev/null
eq "C1 INSERT sem aprovacao: so criada" "$(linhas 101)|$(evento 101 sugestao_criada)" "1|1"
P -q -c "INSERT INTO public.pedido_compra_sugerido (id, status, aprovado_por, aprovado_em, condicao_origem) VALUES (102, 'aprovado_aguardando_disparo', 'u', now(), 'importado_portal');" >/dev/null
eq "C2 INSERT ja aprovado: criada E aprovada" "$(linhas 102)|$(evento 102 sugestao_criada)|$(evento 102 sugestao_aprovada)" "2|1|1"
eq "C2b aprovada do INSERT: props aprovacao_humana=true, status do INSERT" \
   "$(Pq -c "SELECT (props->>'aprovacao_humana') || '|' || (props->>'status') FROM public.analytics_outbox WHERE chave_dedup='pcs:102:reposicao.sugestao_aprovada';")" "true|aprovado_aguardando_disparo"
eq "C2c ordem na fila: criada antes de aprovada (id menor)" \
   "$(Pq -c "SELECT (SELECT id FROM public.analytics_outbox WHERE chave_dedup='pcs:102:reposicao.sugestao_criada') < (SELECT id FROM public.analytics_outbox WHERE chave_dedup='pcs:102:reposicao.sugestao_aprovada');")" "t"
P -q -c "UPDATE public.pedido_compra_sugerido SET aprovado_em = now(), aprovado_por = 'u', status='aprovado_aguardando_disparo' WHERE id = 101;" >/dev/null
eq "C3 UPDATE que aprova: aprovada (ramo velho intacto)" "$(linhas 101)|$(evento 101 sugestao_aprovada)" "2|1"
P -q -c "UPDATE public.pedido_compra_sugerido SET status = 'cancelado' WHERE id = 101;" >/dev/null
eq "C4 UPDATE cancelado (sistema): cancelada com origem_cancelamento=sistema" \
   "$(Pq -c "SELECT props->>'origem_cancelamento' FROM public.analytics_outbox WHERE chave_dedup='pcs:101:reposicao.sugestao_cancelada';")" "sistema"
P -q -c "UPDATE public.pedido_compra_sugerido SET atualizado_em = now() WHERE id = 101;" >/dev/null
eq "C5 UPDATE sem transicao: nenhuma linha nova" "$(linhas 101)" "3"
P -q -c "UPDATE public.pedido_compra_sugerido SET status = 'expirado_sem_aprovacao' WHERE id = 102;" >/dev/null
eq "C6 UPDATE expirado: expirada" "$(evento 102 sugestao_expirada)" "1"
P -q -c "ALTER TABLE public.analytics_outbox ADD CONSTRAINT sabot_fail_open CHECK (evento <> 'reposicao.sugestao_aprovada') NOT VALID;" >/dev/null
P -q -c "INSERT INTO public.pedido_compra_sugerido (id, status, aprovado_por, aprovado_em) VALUES (103, 'aprovado_aguardando_disparo', 'u', now());" > "$RODADA/failopen.log" 2>&1
eq "C7 FAIL-OPEN: outbox recusando, o pedido ainda nasce" "$(Pq -c "SELECT count(*) FROM public.pedido_compra_sugerido WHERE id=103;")" "1"
eq "C7b FAIL-OPEN: WARNING [analytics_outbox] emitido (nao silencio)" "$(grep -c 'WARNING:  \[analytics_outbox\]' "$RODADA/failopen.log")" "1"
P -q -c "ALTER TABLE public.analytics_outbox DROP CONSTRAINT sabot_fail_open;" >/dev/null

# ── ZONA 6: FALSIFICAÇÃO (baseline verde ANTES de sabotar — senão é teatro) ─────────────
echo "── FALSIFICAÇÃO (baseline: $PASS verdes, $FAIL vermelhos) ──"
[ "$FAIL" -eq 0 ] || { echo "baseline vermelha: falsificar nao prova nada"; exit 1; }
FALSIF_OK=0; FALSIF_BAD=0
fok()  { FALSIF_OK=$((FALSIF_OK+1));   echo "  ✅ $1"; }
fbad() { FALSIF_BAD=$((FALSIF_BAD+1)); echo "  ⚠️  $1"; }

# F1: backfill com o predicado sabotado → a POS [BACKFILL] do arquivo tem de ficar VERMELHA.
# Órfã nova: nasce sob o corpo novo (ganha 'aprovada') e perde a linha à mão.
P -q -c "INSERT INTO public.pedido_compra_sugerido (id, status, aprovado_por, aprovado_em, condicao_origem) VALUES (3680, 'disparado', 'u', '2026-10-17 10:00:00+00', 'importado_portal');
         DELETE FROM public.analytics_outbox WHERE chave_dedup = 'pcs:3680:reposicao.sugestao_aprovada';" >/dev/null
perl -0pe "s/WHERE p\.condicao_origem = 'importado_portal'\n    AND p\.aprovado_em IS NOT NULL\n    AND p\.aprovado_em >= '2026-10-14 00:00:00\+00'\n  ON CONFLICT/WHERE p.condicao_origem = 'nunca_importado'\n    AND p.aprovado_em IS NOT NULL\n    AND p.aprovado_em >= '2026-10-14 00:00:00+00'\n  ON CONFLICT/" "$ARQ" > "$RODADA/sab-backfill.sql"
cmp -s "$ARQ" "$RODADA/sab-backfill.sql" && { fbad "F1 a sabotagem do backfill nao mudou o arquivo (regex nao casou)"; }
if P -q -f "$RODADA/sab-backfill.sql" > "$RODADA/f1.log" 2>&1; then fbad "F1 backfill sabotado SEGUIU VERDE: a POS nao tem dente"
elif grep -q 'POS FALHOU \[BACKFILL\]' "$RODADA/f1.log"; then fok "F1 backfill sabotado → POS [BACKFILL] vermelha (1 importado orfao)"
else fbad "F1 vermelha por OUTRO motivo: $(tail -c 300 "$RODADA/f1.log")"; fi
P -q -f "$ARQ" >/dev/null 2>&1 && eq "F1b o arquivo REAL recupera a orfa nova (backfill vivo)" "$(evento 3680 sugestao_aprovada)" "1"

# F2: sem o ramo novo → a POS [RAMO] do arquivo fica VERMELHA, e o corpo sabotado volta a engolir 'aprovada'.
perl -0pe "s/\Qv_eventos := array_append(v_eventos, 'reposicao.sugestao_aprovada');\E/NULL;  -- SABOTADO/" "$ARQ" > "$RODADA/sab-ramo.sql"
cmp -s "$ARQ" "$RODADA/sab-ramo.sql" && { fbad "F2 a sabotagem do ramo nao mudou o arquivo (regex nao casou)"; }
if P -q -f "$RODADA/sab-ramo.sql" > "$RODADA/f2.log" 2>&1; then fbad "F2 ramo removido SEGUIU VERDE: a POS nao tem dente"
elif grep -q 'POS FALHOU \[RAMO\]' "$RODADA/f2.log"; then fok "F2 ramo removido → POS [RAMO] vermelha"
else fbad "F2 vermelha por OUTRO motivo: $(tail -c 300 "$RODADA/f2.log")"; fi
P -q -c "INSERT INTO public.pedido_compra_sugerido (id, status, aprovado_por, aprovado_em) VALUES (201, 'aprovado_aguardando_disparo', 'u', now());" >/dev/null
got="$(linhas 201)"
if [ "$got" = "1" ]; then fok "F2b corpo sabotado volta a emitir so criada (C2 ficaria vermelho: 1 ≠ 2)"
elif [ "$got" = "2" ]; then fbad "F2b corpo sabotado AINDA emite 2 — a asserção C2 nao depende do ramo"
else fbad "F2b corpo sabotado emitiu [$got], nem 1 nem 2"; fi

echo
echo "═══ RESULTADO: $PASS verdes, $FAIL vermelhos · falsificação: $FALSIF_OK com dente, $FALSIF_BAD sem ═══"
[ "$FAIL" -eq 0 ] && [ "$FALSIF_BAD" -eq 0 ]
