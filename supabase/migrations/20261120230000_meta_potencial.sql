-- ── Segmentação de um corte: 1 linha por (conta, cliente) com compra nos 365d antes do corte OU no mês ──
CREATE OR REPLACE FUNCTION public._meta_potencial_clientes(p_corte date)
RETURNS TABLE (account text, customer_user_id uuid, segmento text, rev6 numeric, n6 integer, tick12 numeric, real_mes numeric)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $fn$
  WITH v AS (
    SELECT o.account, o.customer_user_id, o.order_date_kpi AS d, COALESCE(o.total, 0) AS t
    FROM public.sales_orders o
    WHERE o.deleted_at IS NULL
      AND o.status NOT IN ('cancelado', 'rascunho', 'pendente', 'orcamento')
      AND o.customer_user_id IS NOT NULL
      AND o.order_date_kpi >= p_corte - 366
      AND o.order_date_kpi < (p_corte + interval '1 month')::date
  ),
  pre AS (
    SELECT v.account, v.customer_user_id,
           p_corte - max(v.d) AS dias,
           count(DISTINCT date_trunc('month', v.d)) FILTER (WHERE v.d >= (p_corte - interval '6 months')::date) AS n6,
           COALESCE(sum(v.t) FILTER (WHERE v.d >= (p_corte - interval '6 months')::date), 0) AS rev6,
           sum(v.t) FILTER (WHERE v.d >= (p_corte - interval '12 months')::date) AS s12,
           count(DISTINCT date_trunc('month', v.d)) FILTER (WHERE v.d >= (p_corte - interval '12 months')::date) AS m12
    FROM v
    WHERE v.d < p_corte AND v.d >= p_corte - 365
    GROUP BY v.account, v.customer_user_id
  ),
  mes AS (
    SELECT v.account, v.customer_user_id, sum(v.t) AS real_mes
    FROM v WHERE v.d >= p_corte
    GROUP BY v.account, v.customer_user_id
  )
  SELECT COALESCE(pre.account, mes.account),
         COALESCE(pre.customer_user_id, mes.customer_user_id),
         CASE WHEN pre.customer_user_id IS NULL THEN 'N'
              WHEN pre.dias > 180 THEN 'D'
              WHEN pre.dias > 60 THEN 'C'
              WHEN pre.n6 >= 4 THEN 'A'
              ELSE 'B' END,
         COALESCE(pre.rev6, 0),
         COALESCE(pre.n6, 0)::integer,
         CASE WHEN COALESCE(pre.m12, 0) > 0 THEN pre.s12 / pre.m12 ELSE 0 END,
         COALESCE(mes.real_mes, 0)
  FROM pre FULL JOIN mes ON mes.account = pre.account AND mes.customer_user_id = pre.customer_user_id
$fn$;

-- ── Estreias de família no mês do corte (cliente com item nos 12m anteriores, família inédita nesse período) ──
CREATE OR REPLACE FUNCTION public._meta_potencial_estreias(p_corte date)
RETURNS TABLE (account text, valor numeric)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $fn$
  WITH it AS (
    SELECT o.account, o.customer_user_id AS c, p.familia AS f, o.order_date_kpi AS d,
           COALESCE(i.quantity, 0) * COALESCE(i.unit_price, 0) - COALESCE(i.desconto_valor, 0) AS v
    FROM public.order_items i
    JOIN public.sales_orders o ON o.id = i.sales_order_id
    JOIN public.omie_products p ON p.id = i.product_id
    WHERE o.deleted_at IS NULL
      AND o.status NOT IN ('cancelado', 'rascunho', 'pendente', 'orcamento')
      AND o.customer_user_id IS NOT NULL
      AND p.familia IS NOT NULL
      AND o.order_date_kpi >= (p_corte - interval '12 months')::date
      AND o.order_date_kpi < (p_corte + interval '1 month')::date
  ),
  mes AS (SELECT it.account, it.c, it.f, sum(it.v) AS v FROM it WHERE it.d >= p_corte GROUP BY 1, 2, 3)
  SELECT m.account, m.v
  FROM mes m
  WHERE EXISTS (SELECT 1 FROM it a WHERE a.account = m.account AND a.c = m.c AND a.d < p_corte)
    AND NOT EXISTS (SELECT 1 FROM it a WHERE a.account = m.account AND a.c = m.c AND a.f = m.f AND a.d < p_corte)
$fn$;

-- ── Cálculo das linhas (conta × dono) para o mês p_mes ──
CREATE OR REPLACE FUNCTION public._meta_potencial_calcular(p_mes date)
RETURNS TABLE (account text, owner_user_id uuid, owner_ativo boolean, base numeric, esp_c numeric, esp_d numeric,
               novos numeric, inc_c numeric, inc_d numeric, inc_b numeric, inc_cross numeric, taxa_c numeric,
               taxa_d numeric, indice_sazonal numeric, meta numeric, n_a integer, n_b integer, n_c integer, n_d integer)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $fn$
  WITH hist AS (
    SELECT k.corte, c.*
    FROM generate_series((p_mes - interval '12 months')::date, (p_mes - interval '1 month')::date, interval '1 month') AS k(corte)
    CROSS JOIN LATERAL public._meta_potencial_clientes(k.corte::date) c
  ),
  calib AS (
    SELECT h.account,
           CASE WHEN count(DISTINCT h.corte) FILTER (WHERE h.segmento = 'C') >= 6
                 AND sum(h.tick12) FILTER (WHERE h.segmento = 'C') > 0
                THEN sum(h.real_mes) FILTER (WHERE h.segmento = 'C') / sum(h.tick12) FILTER (WHERE h.segmento = 'C') END AS taxa_c,
           CASE WHEN count(DISTINCT h.corte) FILTER (WHERE h.segmento = 'D') >= 6
                 AND sum(h.tick12) FILTER (WHERE h.segmento = 'D') > 0
                THEN sum(h.real_mes) FILTER (WHERE h.segmento = 'D') / sum(h.tick12) FILTER (WHERE h.segmento = 'D') END AS taxa_d,
           CASE WHEN count(DISTINCT h.corte) >= 6
                THEN COALESCE(sum(h.real_mes) FILTER (WHERE h.segmento = 'N'), 0) / count(DISTINCT h.corte) END AS novos
    FROM hist h
    GROUP BY h.account
  ),
  idx AS (
    SELECT CASE WHEN sum(c.rev6) FILTER (WHERE c.segmento IN ('A', 'B')) > 0
                THEN sum(c.real_mes) FILTER (WHERE c.segmento IN ('A', 'B'))
                     / (sum(c.rev6) FILTER (WHERE c.segmento IN ('A', 'B')) / 6) END AS indice
    FROM public._meta_potencial_clientes((p_mes - interval '12 months')::date) c
  ),
  estreia AS (
    SELECT e.account,
           CASE WHEN count(*) >= 20 THEN percentile_cont(0.5) WITHIN GROUP (ORDER BY e.valor)::numeric END AS mediana
    FROM generate_series((p_mes - interval '6 months')::date, (p_mes - interval '1 month')::date, interval '1 month') AS k(corte)
    CROSS JOIN LATERAL public._meta_potencial_estreias(k.corte::date) e
    GROUP BY e.account
  ),
  cur AS (
    SELECT c.account, c.customer_user_id, c.segmento, c.rev6, c.n6, c.tick12, ca.owner_user_id
    FROM public._meta_potencial_clientes(p_mes) c
    LEFT JOIN public.carteira_assignments ca ON ca.customer_user_id = c.customer_user_id AND ca.eligible
    WHERE c.segmento IN ('A', 'B', 'C', 'D')
  ),
  contas AS (SELECT DISTINCT cur.account FROM cur),
  lin AS (
    SELECT cur.account, cur.owner_user_id,
           COALESCE(sum(cur.rev6 / 6) FILTER (WHERE cur.segmento IN ('A', 'B')), 0) AS base,
           COALESCE(sum(cur.tick12) FILTER (WHERE cur.segmento = 'C'), 0) AS tick_c,
           COALESCE(sum(cur.tick12) FILTER (WHERE cur.segmento = 'D'), 0) AS tick_d,
           COALESCE(sum(cur.rev6 / NULLIF(cur.n6, 0)) FILTER (WHERE cur.segmento = 'B'), 0) AS mes_b,
           count(*) FILTER (WHERE cur.segmento = 'A')::integer AS n_a,
           count(*) FILTER (WHERE cur.segmento = 'B')::integer AS n_b,
           count(*) FILTER (WHERE cur.segmento = 'C')::integer AS n_c,
           count(*) FILTER (WHERE cur.segmento = 'D')::integer AS n_d
    FROM cur GROUP BY cur.account, cur.owner_user_id
    UNION ALL  -- garante a linha "sem dono/novos" em toda conta
    SELECT contas.account, NULL::uuid, 0, 0, 0, 0, 0, 0, 0, 0 FROM contas
  ),
  lin2 AS (
    SELECT l.account, l.owner_user_id, sum(l.base) AS base, sum(l.tick_c) AS tick_c, sum(l.tick_d) AS tick_d,
           sum(l.mes_b) AS mes_b, sum(l.n_a)::integer AS n_a, sum(l.n_b)::integer AS n_b,
           sum(l.n_c)::integer AS n_c, sum(l.n_d)::integer AS n_d
    FROM lin l GROUP BY l.account, l.owner_user_id
  ),
  na_conta AS (SELECT l.account, sum(l.n_a) AS n_a FROM lin2 l GROUP BY l.account),
  fim AS (
    SELECT l.account, l.owner_user_id,
           l.owner_user_id IS NOT NULL AND EXISTS (
             SELECT 1 FROM public.sales_orders o
             WHERE o.vendedor_user_id = l.owner_user_id AND o.deleted_at IS NULL
               AND o.status NOT IN ('cancelado', 'rascunho', 'pendente', 'orcamento')
               AND o.order_date_kpi >= p_mes - 60 AND o.order_date_kpi < p_mes) AS owner_ativo,
           round(l.base, 2) AS base,
           round(cb.taxa_c * l.tick_c, 2) AS esp_c,
           round(cb.taxa_d * l.tick_d, 2) AS esp_d,
           CASE WHEN l.owner_user_id IS NULL THEN round(cb.novos, 2) ELSE 0 END AS novos,
           round(0.10 * l.tick_c, 2) AS inc_c,
           round(0.05 * l.tick_d, 2) AS inc_d,
           round(0.10 * l.mes_b, 2) AS inc_b,
           round(CASE WHEN COALESCE(nc.n_a, 0) = 0 THEN 0 ELSE 10 * es.mediana * l.n_a / nc.n_a END, 2) AS inc_cross,
           cb.taxa_c, cb.taxa_d, idx.indice,
           l.n_a, l.n_b, l.n_c, l.n_d
    FROM lin2 l
    LEFT JOIN calib cb ON cb.account = l.account
    LEFT JOIN estreia es ON es.account = l.account
    LEFT JOIN na_conta nc ON nc.account = l.account
    CROSS JOIN idx
  )
  SELECT f.account, f.owner_user_id, f.owner_ativo, f.base, f.esp_c, f.esp_d, f.novos, f.inc_c, f.inc_d, f.inc_b,
         f.inc_cross, round(f.taxa_c, 4), round(f.taxa_d, 4), round(f.indice, 4),
         round((f.base + f.esp_c + f.esp_d + f.novos + f.inc_c + f.inc_d + f.inc_b + f.inc_cross) * round(f.indice, 4), 2),
         f.n_a, f.n_b, f.n_c, f.n_d
  FROM fim f
$fn$;

-- ── Dias úteis do mês por conta (calendario_operacao_empresa guarda só as exceções) ──
CREATE OR REPLACE FUNCTION public._meta_potencial_dia_util(p_account text, p_dia date)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $fn$
  SELECT COALESCE(
    (SELECT c.status <> 'fechado' FROM public.calendario_operacao_empresa c
      WHERE c.empresa = upper(p_account) AND c.data = p_dia),
    extract(isodow FROM p_dia) < 6)
$fn$;

-- ── Escritor único (data injetável só para a prova; o JWT não executa) ──
CREATE OR REPLACE FUNCTION public._meta_potencial_mes_em(p_hoje date, p_user uuid)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = ''
AS $fn$
DECLARE
  c_versao CONSTANT smallint := 1;
  v_mes   date := date_trunc('month', p_hoje)::date;
  v_fim   date := (date_trunc('month', p_hoje) + interval '1 month')::date;
  v_cong  boolean;
  v_linhas jsonb;
  v_dias  jsonb;
BEGIN
  IF p_user IS NOT NULL THEN
    INSERT INTO public.meta_potencial_visualizacao (dia, user_id) VALUES (p_hoje, p_user)
    ON CONFLICT (dia, user_id) DO UPDATE SET n = public.meta_potencial_visualizacao.n + 1;
  END IF;

  v_cong := EXISTS (SELECT 1 FROM public.meta_potencial_mensal m WHERE m.mes = v_mes AND m.versao = c_versao);

  IF NOT v_cong AND extract(day FROM p_hoje) >= 3 THEN
    PERFORM pg_advisory_xact_lock(hashtext('meta_potencial:' || v_mes::text));
    v_cong := EXISTS (SELECT 1 FROM public.meta_potencial_mensal m WHERE m.mes = v_mes AND m.versao = c_versao);
    IF NOT v_cong THEN
      INSERT INTO public.meta_potencial_mensal
        (mes, versao, account, owner_user_id, owner_ativo, base, esp_c, esp_d, novos, inc_c, inc_d, inc_b, inc_cross,
         taxa_c, taxa_d, indice_sazonal, meta, n_a, n_b, n_c, n_d)
      SELECT v_mes, c_versao, k.account, k.owner_user_id, k.owner_ativo, k.base, k.esp_c, k.esp_d, k.novos, k.inc_c,
             k.inc_d, k.inc_b, k.inc_cross, k.taxa_c, k.taxa_d, k.indice_sazonal, k.meta, k.n_a, k.n_b, k.n_c, k.n_d
      FROM public._meta_potencial_calcular(v_mes) k;
      INSERT INTO public.meta_potencial_carteira (mes, versao, account, customer_user_id, owner_user_id, segmento)
      SELECT v_mes, c_versao, c.account, c.customer_user_id, ca.owner_user_id, c.segmento
      FROM public._meta_potencial_clientes(v_mes) c
      LEFT JOIN public.carteira_assignments ca ON ca.customer_user_id = c.customer_user_id AND ca.eligible
      WHERE c.segmento IN ('A', 'B', 'C', 'D');
      v_cong := true;
    END IF;
  END IF;

  IF v_cong THEN
    WITH real AS (
      SELECT o.account, m.owner_user_id, sum(COALESCE(o.total, 0)) AS realizado
      FROM public.sales_orders o
      LEFT JOIN public.meta_potencial_carteira m
        ON m.mes = v_mes AND m.versao = c_versao AND m.account = o.account AND m.customer_user_id = o.customer_user_id
      WHERE o.deleted_at IS NULL AND o.status NOT IN ('cancelado', 'rascunho', 'pendente', 'orcamento')
        AND o.order_date_kpi >= v_mes AND o.order_date_kpi < v_fim
      GROUP BY o.account, m.owner_user_id
    )
    SELECT COALESCE(jsonb_agg(to_jsonb(x) ORDER BY x.account, x.owner_user_id NULLS LAST), '[]'::jsonb) INTO v_linhas
    FROM (
      SELECT k.account, k.owner_user_id, k.owner_ativo,
             (SELECT p.name FROM public.profiles p WHERE p.user_id = k.owner_user_id LIMIT 1) AS owner_nome,
             k.base, k.esp_c, k.esp_d, k.novos, k.inc_c, k.inc_d, k.inc_b, k.inc_cross, k.taxa_c, k.taxa_d,
             k.indice_sazonal, k.meta, k.n_a, k.n_b, k.n_c, k.n_d,
             COALESCE(r.realizado, 0) AS realizado
      FROM public.meta_potencial_mensal k
      LEFT JOIN real r ON r.account = k.account AND r.owner_user_id IS NOT DISTINCT FROM k.owner_user_id
      WHERE k.mes = v_mes AND k.versao = c_versao
    ) x;
  ELSE
    WITH cli AS (
      SELECT c.account, c.customer_user_id, ca.owner_user_id
      FROM public._meta_potencial_clientes(v_mes) c
      LEFT JOIN public.carteira_assignments ca ON ca.customer_user_id = c.customer_user_id AND ca.eligible
      WHERE c.segmento IN ('A', 'B', 'C', 'D')
    ),
    real AS (
      SELECT o.account, m.owner_user_id, sum(COALESCE(o.total, 0)) AS realizado
      FROM public.sales_orders o
      LEFT JOIN cli m ON m.account = o.account AND m.customer_user_id = o.customer_user_id
      WHERE o.deleted_at IS NULL AND o.status NOT IN ('cancelado', 'rascunho', 'pendente', 'orcamento')
        AND o.order_date_kpi >= v_mes AND o.order_date_kpi < v_fim
      GROUP BY o.account, m.owner_user_id
    )
    SELECT COALESCE(jsonb_agg(to_jsonb(x) ORDER BY x.account, x.owner_user_id NULLS LAST), '[]'::jsonb) INTO v_linhas
    FROM (
      SELECT k.*, (SELECT p.name FROM public.profiles p WHERE p.user_id = k.owner_user_id LIMIT 1) AS owner_nome,
             COALESCE(r.realizado, 0) AS realizado
      FROM public._meta_potencial_calcular(v_mes) k
      LEFT JOIN real r ON r.account = k.account AND r.owner_user_id IS NOT DISTINCT FROM k.owner_user_id
    ) x;
  END IF;

  SELECT jsonb_object_agg(a.account, jsonb_build_object(
           'total', (SELECT count(*) FROM generate_series(v_mes, v_fim - 1, interval '1 day') g(d)
                     WHERE public._meta_potencial_dia_util(a.account, g.d::date)),
           'restantes', (SELECT count(*) FROM generate_series(p_hoje, v_fim - 1, interval '1 day') g(d)
                         WHERE public._meta_potencial_dia_util(a.account, g.d::date))))
    INTO v_dias
  FROM (SELECT DISTINCT l ->> 'account' AS account FROM jsonb_array_elements(v_linhas) l) a;

  RETURN jsonb_build_object(
    'mes', v_mes,
    'versao', c_versao,
    'status', CASE WHEN v_cong THEN 'congelada' ELSE 'provisoria' END,
    'linhas', v_linhas,
    'dias_uteis', COALESCE(v_dias, '{}'::jsonb),
    'dias_uteis_grupo', jsonb_build_object(
      'total', (SELECT count(*) FROM generate_series(v_mes, v_fim - 1, interval '1 day') g(d)
                WHERE EXISTS (SELECT 1 FROM (SELECT DISTINCT l ->> 'account' AS account FROM jsonb_array_elements(v_linhas) l) a
                              WHERE public._meta_potencial_dia_util(a.account, g.d::date))),
      'restantes', (SELECT count(*) FROM generate_series(p_hoje, v_fim - 1, interval '1 day') g(d)
                    WHERE EXISTS (SELECT 1 FROM (SELECT DISTINCT l ->> 'account' AS account FROM jsonb_array_elements(v_linhas) l) a
                                  WHERE public._meta_potencial_dia_util(a.account, g.d::date))))
  );
END
$fn$;

-- ── Fronteira do JWT: master-only, hoje = agora em São Paulo ──
CREATE OR REPLACE FUNCTION public.meta_potencial_mes()
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = ''
AS $fn$
DECLARE
  v_uid uuid := (SELECT auth.uid());
BEGIN
  IF v_uid IS NULL OR NOT public.has_role(v_uid, 'master'::public.app_role) THEN
    RAISE EXCEPTION 'forbidden: meta_potencial_mes exige master' USING ERRCODE = '42501';
  END IF;
  RETURN public._meta_potencial_mes_em((now() AT TIME ZONE 'America/Sao_Paulo')::date, v_uid);
END
$fn$;

REVOKE ALL ON FUNCTION public._meta_potencial_clientes(date) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public._meta_potencial_estreias(date) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public._meta_potencial_calcular(date) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public._meta_potencial_dia_util(text, date) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public._meta_potencial_mes_em(date, uuid) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.meta_potencial_mes() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.meta_potencial_mes() TO authenticated;

-- ── Postcondição ──────────────────────────────────────────────
DO $post$
DECLARE
  t text;
  f text;
BEGIN
  FOREACH t IN ARRAY ARRAY['public.meta_potencial_mensal', 'public.meta_potencial_carteira', 'public.meta_potencial_visualizacao'] LOOP
    IF to_regclass(t) IS NULL
       OR NOT (SELECT relrowsecurity FROM pg_class WHERE oid = t::regclass)
       OR has_table_privilege('authenticated', t, 'SELECT') OR has_table_privilege('anon', t, 'SELECT')
       OR has_table_privilege('authenticated', t, 'INSERT') THEN
      RAISE EXCEPTION 'C1 FALHOU: % ausente, sem RLS ou acessivel pelo JWT', t;
    END IF;
  END LOOP;
  FOREACH f IN ARRAY ARRAY['public._meta_potencial_clientes(date)', 'public._meta_potencial_estreias(date)',
                           'public._meta_potencial_calcular(date)', 'public._meta_potencial_dia_util(text,date)',
                           'public._meta_potencial_mes_em(date,uuid)'] LOOP
    IF to_regprocedure(f) IS NULL OR has_function_privilege('public', f, 'EXECUTE')
       OR has_function_privilege('anon', f, 'EXECUTE') OR has_function_privilege('authenticated', f, 'EXECUTE') THEN
      RAISE EXCEPTION 'C2 FALHOU: helper % ausente ou executavel pelo JWT', f;
    END IF;
  END LOOP;
  f := 'public.meta_potencial_mes()';
  IF to_regprocedure(f) IS NULL OR has_function_privilege('public', f, 'EXECUTE')
     OR has_function_privilege('anon', f, 'EXECUTE') OR NOT has_function_privilege('authenticated', f, 'EXECUTE') THEN
    RAISE EXCEPTION 'C3 FALHOU: % ausente ou com ACL errada', f;
  END IF;
  RAISE NOTICE 'meta_potencial OK';
END
