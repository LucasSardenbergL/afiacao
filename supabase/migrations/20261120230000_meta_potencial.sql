-- ============================================================
-- meta_potencial — meta mensal por potencial da carteira (Meu dia do CEO, leva 2).
--
-- Por quê: o card "Receita time · mês" não tinha alvo; o founder recusou meta fixa de grupo e aprovou
-- "previsão calibrada + incremento por alavanca". Spec: docs/superpowers/specs/2026-11-20-meta-potencial-vendedora-design.md
--
-- Meta (por conta × dono da carteira) = (base A+B + retorno espontâneo C/D + novos + incrementos) × índice sazonal.
--   - Segmentos exclusivos, RECÊNCIA primeiro: >365d fora · 181–365 D · 61–180 C · ≤60 & ≥4 de 6 meses A · ≤60 B.
--   - Taxas espontâneas C/D e novos calibrados nos 12 cortes anteriores (pooled, ≥6 cortes com dado).
--   - Índice = realizado A+B ÷ base A+B do GRUPO no corte do mesmo mês do ano anterior.
--   - Ausente ≠ zero: qualquer calibração ausente → meta NULL (nunca índice 1 / taxa 0 silenciosos).
-- Congela no 1º acesso a partir do dia 3 (SP); dias 1–2 → provisória, nada gravado. Só o mês corrente.
-- Ledger: meta_potencial_mensal + meta_potencial_carteira (quem estava em qual segmento: base para medir o
-- efeito depois) + meta_potencial_visualizacao (SENSOR de uso). Escritor único: _meta_potencial_mes_em().
-- ============================================================

CREATE TABLE IF NOT EXISTS public.meta_potencial_mensal (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mes            date NOT NULL CHECK (extract(day FROM mes) = 1),
  versao         smallint NOT NULL,
  account        text NOT NULL,
  owner_user_id  uuid,                 -- null = sem dono na carteira + clientes novos
  owner_ativo    boolean NOT NULL,
  base           numeric NOT NULL,
  esp_c          numeric,
  esp_d          numeric,
  novos          numeric,
  inc_c          numeric NOT NULL,
  inc_d          numeric NOT NULL,
  inc_b          numeric NOT NULL,
  inc_cross      numeric,
  taxa_c         numeric,
  taxa_d         numeric,
  indice_sazonal numeric,
  meta           numeric,              -- null = calibração ausente (meta indisponível)
  n_a            integer NOT NULL,
  n_b            integer NOT NULL,
  n_c            integer NOT NULL,
  n_d            integer NOT NULL,
  calculado_em   timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_meta_potencial_mensal
  ON public.meta_potencial_mensal (mes, versao, account, COALESCE(owner_user_id, '00000000-0000-0000-0000-000000000000'::uuid));

CREATE TABLE IF NOT EXISTS public.meta_potencial_carteira (
  mes              date NOT NULL,
  versao           smallint NOT NULL,
  account          text NOT NULL,
  customer_user_id uuid NOT NULL,
  owner_user_id    uuid,
  segmento         text NOT NULL CHECK (segmento IN ('A', 'B', 'C', 'D')),
  PRIMARY KEY (mes, versao, account, customer_user_id)
);

CREATE TABLE IF NOT EXISTS public.meta_potencial_visualizacao (
  dia     date NOT NULL,
  user_id uuid NOT NULL,
  n       integer NOT NULL DEFAULT 1 CHECK (n >= 1),
  PRIMARY KEY (dia, user_id)
);

ALTER TABLE public.meta_potencial_mensal       ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.meta_potencial_carteira     ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.meta_potencial_visualizacao ENABLE ROW LEVEL SECURITY;
