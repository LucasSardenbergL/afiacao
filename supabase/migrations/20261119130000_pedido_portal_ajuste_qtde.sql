-- ============================================================
-- pedido_portal_ajuste_qtde — ledger do ajuste de lote mínimo no portal Sayerlack [money-path]
-- Spec: docs/superpowers/specs/2026-11-18-sayerlack-lote-minimo-portal-design.md (Fase 1 revisada)
--
-- Quando o portal recusa um item por "lote mínimo de venda (N)", a edge enviar-pedido-portal-sayerlack
-- sobe a Qtd UN ao lote, efetiva, e o PO do Omie segue com a qtde REAL (qtde_final). A divergência
-- portal ≠ Omie é INTENCIONAL e mora AQUI — 1 linha por item ajustado.
--
-- 1 escritor: a edge (service role). Leitura: staff. Sem policy de escrita para authenticated.
-- A Fase 2 acrescenta a trilha do e-mail ao CRS (thread, cobrança, resposta) e as transições de status.
-- Idempotente: rodar 2× não falha nem duplica.
-- ============================================================
BEGIN;

CREATE TABLE IF NOT EXISTS public.pedido_portal_ajuste_qtde (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id bigint NOT NULL REFERENCES public.pedido_compra_sugerido(id) ON DELETE RESTRICT,
  -- Sem FK de propósito: o ledger é auditoria e sobrevive à linha do item (o id fica como prova).
  pedido_item_id bigint NOT NULL,
  empresa text NOT NULL,
  sku_portal text NOT NULL,
  sku_codigo_omie text,
  -- Unidade do Omie (= qtde_final aprovada, a que vai no PO).
  qtde_omie numeric NOT NULL CHECK (qtde_omie > 0),
  -- Qtd UN do portal: a necessária (convertida da qtde_final) e a lançada (= lote).
  qtde_portal_necessaria integer NOT NULL CHECK (qtde_portal_necessaria > 0),
  qtde_portal_lancada integer NOT NULL,
  lote_minimo integer NOT NULL,
  portal_protocolo text,
  -- Status do envio no momento do registro (sucesso_portal | aceito_portal_sem_protocolo | indeterminado_requer_conciliacao).
  status_envio text NOT NULL,
  status text NOT NULL DEFAULT 'pendente_email'
    CHECK (status IN ('pendente_email', 'email_enviado', 'aceito', 'recusado',
                      'cancelamento_pedido', 'cancelado', 'lote_aceito')),
  evidencia jsonb NOT NULL DEFAULT '{}'::jsonb,
  criado_em timestamptz NOT NULL DEFAULT now(),
  criado_por text NOT NULL DEFAULT 'sistema',
  CONSTRAINT pedido_portal_ajuste_qtde_lote_coerente
    CHECK (qtde_portal_lancada = lote_minimo AND lote_minimo > qtde_portal_necessaria),
  CONSTRAINT pedido_portal_ajuste_qtde_item_uniq UNIQUE (pedido_id, pedido_item_id)
);

CREATE INDEX IF NOT EXISTS idx_pedido_portal_ajuste_qtde_status
  ON public.pedido_portal_ajuste_qtde(status, criado_em);

ALTER TABLE public.pedido_portal_ajuste_qtde ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "pedido_portal_ajuste_qtde_select_staff" ON public.pedido_portal_ajuste_qtde;
CREATE POLICY "pedido_portal_ajuste_qtde_select_staff"
  ON public.pedido_portal_ajuste_qtde
  FOR SELECT
  TO authenticated
  USING (
    (SELECT public.has_role(auth.uid(), 'employee'::public.app_role))
    OR (SELECT public.has_role(auth.uid(), 'master'::public.app_role))
  );

-- Escrita só pela edge (service_role ignora RLS); anon/authenticated sem privilégio de escrita.
REVOKE ALL ON public.pedido_portal_ajuste_qtde FROM PUBLIC, anon;
REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON public.pedido_portal_ajuste_qtde FROM authenticated;
GRANT SELECT ON public.pedido_portal_ajuste_qtde TO authenticated;
GRANT ALL ON public.pedido_portal_ajuste_qtde TO service_role;

DO $post$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relname = 'pedido_portal_ajuste_qtde' AND c.relrowsecurity
  ) THEN
    RAISE EXCEPTION 'A1 FALHOU: pedido_portal_ajuste_qtde ausente ou sem RLS — ledger do lote mínimo exposto ou inexistente';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.pedido_portal_ajuste_qtde'::regclass
      AND conname = 'pedido_portal_ajuste_qtde_item_uniq' AND contype = 'u' AND convalidated
  ) THEN
    RAISE EXCEPTION 'A2 FALHOU: UNIQUE (pedido_id, pedido_item_id) ausente — retentativa duplicaria o ajuste';
  END IF;
  IF has_table_privilege('authenticated', 'public.pedido_portal_ajuste_qtde', 'INSERT')
     OR has_table_privilege('anon', 'public.pedido_portal_ajuste_qtde', 'SELECT') THEN
    RAISE EXCEPTION 'A3 FALHOU: authenticated pode escrever ou anon pode ler — 1 escritor (edge) violado';
  END IF;
  RAISE NOTICE 'pedido_portal_ajuste_qtde OK: RLS, UNIQUE e privilégios provados';
END
$post$;

COMMIT;
