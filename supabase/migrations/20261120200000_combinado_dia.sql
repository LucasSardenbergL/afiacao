-- ============================================================
-- combinado_dia — o "Combinado do dia" que o CEO encaminhou a cada vendedora (Meu dia do master).
--
-- Por quê: o app tem recompra atrasada (R$ 351k) e cobrança vencida (Oben R$ 345k) listadas, e ZERO ação
-- registrada (venda_contato e cobranca_evento com 0 linha). O combinado é a rotina de adoção: o CEO escolhe até
-- 3 clientes por vendedora e encaminha o texto no WhatsApp. Esta tabela é o SENSOR dessa superfície (regra de
-- fase: superfície nasce com o sensor, no ledger — o PostHog é cego para o founder) e a LISTA DATADA que permite
-- cruzar, depois, com pedidos/recebimentos dos mesmos clientes.
--
-- Escritor único: combinado_registrar(). 1 linha por (dia SP, vendedora); re-copiar no mesmo dia atualiza os
-- itens e soma n_copias. Leitura: só service_role/psql (medição), sem policy para o JWT.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.combinado_dia (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dia           date NOT NULL,
  master_id     uuid NOT NULL,
  vendedora_id  uuid NOT NULL,
  -- [{tipo: 'cobranca'|'recompra', empresa, cliente_ref, nome, valor}] — o que foi proposto, para cruzar depois.
  itens         jsonb NOT NULL CHECK (jsonb_typeof(itens) = 'array'
                                      AND jsonb_array_length(itens) BETWEEN 1 AND 3),
  n_copias      integer NOT NULL DEFAULT 1 CHECK (n_copias >= 1),
  criado_em     timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  UNIQUE (dia, vendedora_id)
);
CREATE INDEX IF NOT EXISTS idx_combinado_dia_vendedora ON public.combinado_dia (vendedora_id, dia);
ALTER TABLE public.combinado_dia ENABLE ROW LEVEL SECURITY;
-- Sem policy de propósito: o front só passa pela RPC; a medição lê como service_role/psql.
REVOKE ALL ON TABLE public.combinado_dia FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT ON TABLE public.combinado_dia TO service_role;
COMMENT ON TABLE public.combinado_dia IS
  'Combinado do dia (Meu dia do master): até 3 clientes (cobrança/recompra) por vendedora, encaminhados pelo CEO. '
  '1 linha por dia SP + vendedora; n_copias = quantas vezes o texto foi copiado. Escritor único: '
  'combinado_registrar(). Migration 20261120200000.';

CREATE OR REPLACE FUNCTION public.combinado_registrar(p_vendedora uuid, p_itens jsonb)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = ''
AS $fn$
DECLARE
  v_uid uuid := (SELECT auth.uid());
  v_it  jsonb;
BEGIN
  IF v_uid IS NULL OR NOT public.has_role(v_uid, 'master'::public.app_role) THEN
    RAISE EXCEPTION 'forbidden: combinado_registrar exige master' USING ERRCODE = '42501';
  END IF;
  IF p_vendedora IS NULL OR NOT (public.has_role(p_vendedora, 'employee'::public.app_role)
                                 OR public.has_role(p_vendedora, 'master'::public.app_role)) THEN
    RAISE EXCEPTION 'vendedora invalida (nao e staff)' USING ERRCODE = '22023';
  END IF;
  IF p_itens IS NULL OR jsonb_typeof(p_itens) <> 'array' OR jsonb_array_length(p_itens) NOT BETWEEN 1 AND 3 THEN
    RAISE EXCEPTION 'itens: array de 1 a 3' USING ERRCODE = '22023';
  END IF;
  FOR v_it IN SELECT * FROM jsonb_array_elements(p_itens) LOOP
    IF jsonb_typeof(v_it) <> 'object' OR COALESCE(v_it ->> 'tipo', '') NOT IN ('cobranca', 'recompra')
       OR COALESCE(v_it ->> 'cliente_ref', '') = '' THEN
      RAISE EXCEPTION 'item invalido: exige tipo (cobranca|recompra) e cliente_ref' USING ERRCODE = '22023';
    END IF;
  END LOOP;

  INSERT INTO public.combinado_dia (dia, master_id, vendedora_id, itens)
  VALUES ((now() AT TIME ZONE 'America/Sao_Paulo')::date, v_uid, p_vendedora, p_itens)
  ON CONFLICT (dia, vendedora_id) DO UPDATE
    SET itens = EXCLUDED.itens,
        master_id = EXCLUDED.master_id,
        n_copias = public.combinado_dia.n_copias + 1,
        atualizado_em = now();
  RETURN jsonb_build_object('ok', true);
END
$fn$;
REVOKE ALL ON FUNCTION public.combinado_registrar(uuid, jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.combinado_registrar(uuid, jsonb) TO authenticated;

-- ── Postcondição ──────────────────────────────────────────────
DO $post$
DECLARE
  f text := 'public.combinado_registrar(uuid,jsonb)';
BEGIN
  IF to_regclass('public.combinado_dia') IS NULL
     OR NOT (SELECT relrowsecurity FROM pg_class WHERE oid = 'public.combinado_dia'::regclass)
     OR has_table_privilege('authenticated', 'public.combinado_dia', 'SELECT')
     OR has_table_privilege('anon', 'public.combinado_dia', 'SELECT') THEN
    RAISE EXCEPTION 'C1 FALHOU: combinado_dia ausente, sem RLS ou legivel pelo JWT';
  END IF;
  IF to_regprocedure(f) IS NULL
     OR has_function_privilege('public', f, 'EXECUTE') OR has_function_privilege('anon', f, 'EXECUTE')
     OR NOT has_function_privilege('authenticated', f, 'EXECUTE') THEN
    RAISE EXCEPTION 'C2 FALHOU: % ausente ou com ACL errada', f;
  END IF;
  RAISE NOTICE 'combinado_dia + combinado_registrar OK';
END
$post$;
